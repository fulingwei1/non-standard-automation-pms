def main():
    conn = sqlite3.connect(DB_PATH)
    conn.execute("DELETE FROM company_profile")  # 清空重导

    for i, (cat, key, content) in enumerate(PROFILES):
        conn.execute(
            "INSERT INTO company_profile (category, key, content, sort_order, is_active, created_at, updated_at) "
            "VALUES (?,?,?,?,1, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP)",
            (cat, key, content, i),
        )

    conn.commit()
    count = conn.execute("SELECT COUNT(*) FROM company_profile").fetchone()[0]
    print(f"完成：导入 {count} 条公司知识")

    # 按分类统计
    print("\n分类统计:")
    for row in conn.execute("SELECT category, COUNT(*) FROM company_profile GROUP BY category"):
        print(f"  {row[0]}: {row[1]} 条")

    # 抽样
    print("\n抽样:")
    for row in conn.execute("SELECT category, key, substr(content,1,80) FROM company_profile LIMIT 4"):
        print(f"\n  [{row[0]}] {row[1]}")
        print(f"  {row[2]}...")
    conn.close()


if __name__ == "__main__":
    main()
